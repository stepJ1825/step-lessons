-- 1. Создание таблиц
CREATE TABLE customers
(
    id   UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE orders
(
    id          UUID PRIMARY KEY,
    title       VARCHAR(500) NOT NULL,
    price       DECIMAL      NOT NULL,
    customer_id UUID REFERENCES customers (id)
);

