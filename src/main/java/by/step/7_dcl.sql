--DCL (Data Control Language) команд в PostgreSQL. DCL отвечает за управление правами доступа и ролями (пользователями).
--💡 В PostgreSQL нет классических SQL-команд GRANT OPTION или DENY — вместо этого используется гибкая система ролей и привилегий через GRANT и REVOKE.
-- =============================================================================
-- Файл: dcl_examples.sql
-- Описание: Примеры всех основных DCL-команд в PostgreSQL
-- DCL = Data Control Language: GRANT, REVOKE, CREATE ROLE, ALTER ROLE, DROP ROLE
-- Примечание: Для демонстрации создаются роли и таблица.
-- =============================================================================

-- 1. Подготовка: создание тестовой таблицы (не DCL, но нужно для примеров)
CREATE TABLE IF NOT EXISTS projects (
    id SERIAL PRIMARY KEY,
    name TEXT NOT NULL,
    budget NUMERIC(12, 2)
);

-- Очистка данных (если таблица уже существует)
TRUNCATE projects;

-- Вставка тестовых данных
INSERT INTO projects (name, budget)
VALUES
    ('Сайт компании', 500000.00),
    ('Мобильное приложение', 1200000.00);

-- =============================================================================
-- 2. CREATE ROLE — создание ролей (аналог "пользователей" или "групп")
-- =============================================================================

-- Создание роли-пользователя с возможностью входа
CREATE ROLE analyst LOGIN PASSWORD 'secure_password123';

-- Создание роли без возможности входа (групповая роль)
CREATE ROLE developers;

-- Создание роли с правом создания БД и ролей
CREATE ROLE admin_user
    LOGIN
    PASSWORD 'admin_pass'
    CREATEDB
    CREATEROLE;

-- =============================================================================
-- 3. GRANT — предоставление привилегий
-- =============================================================================

-- Предоставление права SELECT на таблицу конкретной роли
GRANT SELECT ON TABLE projects TO analyst;

-- Предоставление нескольких привилегий
GRANT INSERT, UPDATE ON TABLE projects TO analyst;

-- Предоставление всех привилегий на таблицу
GRANT ALL PRIVILEGES ON TABLE projects TO admin_user;

-- Предоставление права использовать последовательность (важно для SERIAL!)
GRANT USAGE, SELECT ON SEQUENCE projects_id_seq TO analyst;

-- Предоставление роли другой роли (наследование)
GRANT developers TO analyst;

-- Предоставление права подключаться к базе данных
GRANT CONNECT ON DATABASE postgres TO analyst;  -- замените "postgres" на имя вашей БД

-- Предоставление права использовать схему
GRANT USAGE ON SCHEMA public TO analyst;

-- Предоставление права создавать объекты в схеме
GRANT CREATE ON SCHEMA public TO developers;

-- =============================================================================
-- 4. REVOKE — отзыв привилегий
-- =============================================================================

-- Отзыв права UPDATE у роли
REVOKE UPDATE ON TABLE projects FROM analyst;

-- Отзыв всех привилегий на таблицу
REVOKE ALL PRIVILEGES ON TABLE projects FROM admin_user;

-- Отзыв права использования последовательности
REVOKE USAGE ON SEQUENCE projects_id_seq FROM analyst;

-- Отзыв роли (удаление из группы)
REVOKE developers FROM analyst;

-- Отзыв права подключения к БД
REVOKE CONNECT ON DATABASE postgres FROM analyst;

-- =============================================================================
-- 5. ALTER ROLE — изменение параметров роли
-- =============================================================================

-- Смена пароля
ALTER ROLE analyst PASSWORD 'new_secure_password456';

-- Блокировка входа (отзыв LOGIN)
ALTER ROLE analyst NOLOGIN;

-- Разрешить вход снова
ALTER ROLE analyst LOGIN;

-- Установка временной зоны по умолчанию для роли
ALTER ROLE analyst SET timezone TO 'Europe/Moscow';

-- Сброс параметра к значению по умолчанию
ALTER ROLE analyst RESET timezone;

-- =============================================================================
-- 6. DROP ROLE — удаление роли
-- =============================================================================

-- Удаление роли (должна быть без зависимостей)
DROP ROLE IF EXISTS analyst;

-- Удаление групповой роли
DROP ROLE IF EXISTS developers;

-- Удаление администратора
DROP ROLE IF EXISTS admin_user;

-- =============================================================================
-- 7. Дополнительно: проверка текущих привилегий
-- (Это не DCL, но полезно для отладки)
-- =============================================================================

-- Просмотр привилегий на таблицу (выполняется от имени владельца или суперпользователя)
-- \dp projects

-- Просмотр ролей в psql:
-- \du

-- SQL-запрос для просмотра привилегий:
SELECT grantee, privilege_type
FROM information_schema.role_table_grants
WHERE table_name = 'projects';

-- =============================================================================
-- Завершение: очистка
-- =============================================================================
DROP TABLE IF EXISTS projects;



--Важные замечания:
--GRANT и REVOKE — основные DCL-команды в PostgreSQL.
--PostgreSQL использует роли, а не отдельные понятия "пользователь" и "группа". Роль с атрибутом LOGIN — это пользователь.
--Нет команды DENY — если привилегия не предоставлена, она не действует (модель "разрешено только явно").
--Чтобы команды работали, вы должны быть:
--владельцем объекта, или
--суперпользователем, или
--иметь право GRANT OPTION (в PostgreSQL это автоматически даётся владельцу).
--Имя базы данных в GRANT CONNECT замените на актуальное (например, myapp_db).
--Как выполнить:
--psql -U postgres -d your_database -f dcl_examples.sql
--⚠️ Некоторые команды (например, CREATE ROLE с PASSWORD) могут требовать подключения от суперпользователя.
